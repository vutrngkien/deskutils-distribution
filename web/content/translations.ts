/**
 * Utility pages share one template. Their required keys are derived from the
 * data module plus the template chrome, so the spec and the checker stay in
 * sync without a 300-line literal.
 */
function utilityRequiredKeys(id: string): MessageKey[] {
  const page = utilityPages[id];
  const keys: MessageKey[] = [
    ...utilityCommonKeys,
    `meta.${id}.title` as MessageKey,
    `meta.${id}.description` as MessageKey,
    page.altKey,
    page.eyebrow,
    page.title,
    page.desc,
    page.shortcutNote,
    page.howTitle,
    page.howDesc,
    page.permission,
  ];
  for (const item of page.related) {
    keys.push(item.name, item.body);
  }
  for (const faq of page.faqs) {
    keys.push(faq.question, faq.answer);
  }
  return keys;
}

for (const id of utilityIds) {
  routeRequiredKeys[id] = utilityRequiredKeys(id);
}

