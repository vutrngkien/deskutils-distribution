/**
 * Declared completeness per route. The homepage was rebuilt in English only.
 * Install/Privacy/Terms/Feedback remain complete for the fully-translated
 * catalogs (de, es, fr, ja, vi, zh-CN). ko, ru and zh-TW rely on English/
 * Simplified fallback spreads, so they are intentionally NOT declared complete
 * and their localized pages are noindex until genuinely translated.
 */
export const routeTranslations: Record<string, Locale[]> = {
  home: ['en'],
  install: ['en', 'de', 'es', 'fr', 'ja', 'vi', 'zh-CN'],
  privacy: ['en', 'de', 'es', 'fr', 'ja', 'vi', 'zh-CN'],
  terms: ['en', 'de', 'es', 'fr', 'ja', 'vi', 'zh-CN'],
  feedback: ['en', 'de', 'es', 'fr', 'ja', 'vi', 'zh-CN'],
};

export function sharedKeys(): MessageKey[] {
  return sharedRequiredKeys;
}

export function routeRequiredKeysFor(id: string): MessageKey[] {
  return routeRequiredKeys[id] ?? [];
}

export function translatedLocalesFor(id: string): Locale[] {
  return routeTranslations[id] ?? [];
}

export function isRouteComplete(locale: Locale, id: string): boolean {
  return translatedLocalesFor(id).includes(locale);
}

export { en, languages };
